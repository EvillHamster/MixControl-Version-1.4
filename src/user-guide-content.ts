export function getUserGuide(role: Role): {
  roleName: string;
  sections: Section[];
} {
  if (role === "EMPLOYEE")
    return {
      roleName: "Сотрудник",
      sections: [
        {
          title: "Ваши разделы",
          steps: ["Вам доступны «Журнал контроля» и «Ежедневные отчёты»."],
        },
        measurement,
        {
          title: "Исправление своих записей",
          steps: [
            "В своей записи нажмите карандаш и исправьте SUP или смесь. После сохранения обе температуры останутся прежними.",
            "При смене смеси подставляются её нормативы и пересчитывается результат. Изменение только SUP сохраняет прежние нормативы.",
            "Сохранённые температуры и чужие записи редактировать нельзя. Удаление измерений, управление смесями и пользователями вам недоступны.",
          ],
        },
        results,
        journal,
        reports,
      ],
    };
  const keyuser = role === "KEYUSER";
  return {
    roleName: keyuser ? "KEYUSER" : "Администратор",
    sections: [
      {
        title: "Ваши разделы",
        steps: [
          "Доступны «Журнал контроля», «База смесей», «Ежедневные отчёты», «Корректирующие действия» и «Пользователи»." +
            (keyuser
              ? " Настройки собственного аккаунта открываются кнопкой с шестерёнкой у профиля."
              : ""),
        ],
      },
      measurement,
      results,
      journal,
      managerJournal,
      library,
      reports,
      corrections(keyuser),
      transfer,
      {
        title: "Пользователи",
        steps: keyuser
          ? [
              "Добавляйте сотрудников и администраторов. Редактируйте разрешённые данные аккаунтов, задавайте новый пароль, меняйте роли или отключайте доступ.",
              "В системе может быть только один KEYUSER. Нельзя удалить, отключить или понизить единственного активного KEYUSER.",
              "Удаление аккаунта завершает его сессии и освобождает логин. Созданные им измерения и техническая история сохраняются.",
            ]
          : [
              "Можно создавать сотрудников и администраторов. Изменять данные, пароль, роль, блокировать или удалять существующий аккаунт можно только у EMPLOYEE.",
              "Управление аккаунтами ADMIN и KEYUSER и назначение роли KEYUSER недоступны.",
              "Удаление сотрудника освобождает его логин и завершает сессии, сохраняя производственные измерения и историю.",
            ],
      },
      ...(keyuser
        ? [
            {
              title: "Свой логин и пароль",
              steps: [
                "В настройках аккаунта логин и пароль меняются отдельно. Для каждого изменения введите текущий пароль.",
                "После сохранения войдите снова с новыми данными. Прежние данные входа больше не подходят.",
              ],
            },
          ]
        : []),
    ],
  };
}
